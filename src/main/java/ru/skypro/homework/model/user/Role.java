package ru.skypro.homework.model.user;

/**
 * Роль пользователя в системе.
 * <p>
 * Определяет уровень доступа к функциональности приложения.
 * </p>
 */
public enum Role {
    /** Обычный пользователь — может создавать объявления и оставлять комментарии. */
    USER,
    /** Администратор — имеет полный доступ ко всем функциям системы. */
    ADMIN
}
